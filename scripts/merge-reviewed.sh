#!/usr/bin/env bash
# Squash merge a pull request only after a clean review of its current commit.
#
# Usage: scripts/merge-reviewed.sh <pr> <issue> <subject> <body-file>
#
# Waits for the latest review's first line to read "Blockers: 0 at <head>", then
# for CI. It brings a stale branch up to date, and refuses to merge if that
# changes the reviewed patch. It stops without merging on any other outcome.
# Run it from a clone of the repository, with gh signed in.
set -uo pipefail

pr=${1:?usage: merge-reviewed.sh <pr> <issue> <subject> <body-file>}
issue=${2:?missing issue}
subject=${3:?missing subject}
body=${4:?missing body file}
project=PVT_kwHOEgpewc4BonJD
status_field=PVTSSF_lAHOEgpewc4BonJDzhnGbck
done_option=1f86c1ca

stop() {
  echo "STOP $pr: $1"
  exit 1
}

head_of() { gh pr view "$pr" --json headRefOid --jq .headRefOid; }

patch_of() {
  git fetch -q origin main "$1" || stop "cannot fetch $1"
  git diff "$(git merge-base origin/main "$1")" "$1" | git patch-id --stable | cut -d' ' -f1
}

deadline=$(($(date +%s) + 2700))
while :; do
  [ "$(date +%s)" -lt "$deadline" ] || stop "no verdict at the current head in time"
  reviewed=$(head_of)
  verdict=$(gh pr view "$pr" --json reviews --jq '.reviews[-1].body // "" | split("\n")[0]')
  case "$verdict" in
    "Blockers: 0 at $reviewed") break ;;
    "Blockers: "*" at $reviewed") stop "$verdict" ;;
  esac
  sleep 45
done

reviewed_patch=$(patch_of "$reviewed")
state=$(gh pr view "$pr" --json mergeStateStatus --jq .mergeStateStatus)
if [ "$state" = BEHIND ]; then
  gh pr update-branch "$pr" >/dev/null || stop "cannot update the branch"
  sleep 20
fi

deadline=$(($(date +%s) + 1500))
while :; do
  [ "$(date +%s)" -lt "$deadline" ] || stop "CI timeout"
  checks=$(gh pr view "$pr" --json statusCheckRollup \
    --jq '[.statusCheckRollup[] | (if (.conclusion // "") == "" then "RUNNING" else .conclusion end)] | join(",")')
  case "$checks" in
    "" | *RUNNING*) sleep 30 ;;
    SUCCESS,SUCCESS) break ;;
    *) stop "checks $checks" ;;
  esac
done

head=$(head_of)
[ "$(patch_of "$head")" = "$reviewed_patch" ] || stop "patch at $head differs from reviewed $reviewed"

gh pr ready "$pr" >/dev/null 2>&1
current=$(mktemp)
trap 'rm -f "$current"' EXIT
# Session links stay out of public pull requests.
gh pr view "$pr" --json body --jq .body |
  sed -E 's#^_Generated by \[Claude Code\]\(https://claude.ai/code/session_[A-Za-z0-9]+\)_$#🤖 Generated with [Claude Code](https://claude.com/claude-code)#' >"$current"
gh pr edit "$pr" --body-file "$current" >/dev/null

if ! gh pr merge "$pr" --squash --match-head-commit "$head" --subject "$subject" --body-file "$body"; then
  sleep 15
  gh pr merge "$pr" --squash --match-head-commit "$head" --subject "$subject" --body-file "$body" ||
    stop "merge refused"
fi

item=$(gh project item-list 3 --owner slackysoba --format json --limit 200 --jq ".items[] | select(.content.number==$issue) | .id")
if [ -n "$item" ]; then
  gh project item-edit --project-id "$project" --id "$item" --field-id "$status_field" \
    --single-select-option-id "$done_option" --format json --jq .id >/dev/null
fi
echo "MERGED $pr as $(gh pr view "$pr" --json mergeCommit --jq .mergeCommit.oid) at reviewed patch $reviewed_patch"
